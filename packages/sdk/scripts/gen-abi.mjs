// Regenerates src/abi.ts from the Foundry build output.
// Usage: (cd contracts && forge build) && pnpm --filter @blindspot/sdk gen:abi
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../../contracts/out/BlindspotMarkets.sol/BlindspotMarkets.json");
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));

const out = `// AUTO-GENERATED by scripts/gen-abi.mjs from contracts/out — do not edit by hand.
export const blindspotMarketsAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
writeFileSync(resolve(here, "../src/abi.ts"), out);
console.log(`wrote src/abi.ts (${abi.length} entries)`);
